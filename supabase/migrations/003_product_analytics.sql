-- v95 privacy-safe product telemetry.
-- Only the Edge Function service-role writes/reads this table; no anon/client policies are added.
create table if not exists public.app_telemetry_events (
  id bigint generated by default as identity primary key,
  event_id uuid not null unique,
  account_id uuid not null references public.app_accounts(id) on delete cascade,
  event_name text not null,
  event_at timestamptz not null,
  app_version text not null default 'unknown',
  device_name text,
  properties jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint app_telemetry_event_name_len check (char_length(event_name) between 1 and 48),
  constraint app_telemetry_version_len check (char_length(app_version) between 1 and 20),
  constraint app_telemetry_device_len check (device_name is null or char_length(device_name) <= 80)
);

alter table public.app_telemetry_events enable row level security;

create index if not exists app_telemetry_event_at_idx
  on public.app_telemetry_events(event_at desc);

create index if not exists app_telemetry_account_event_idx
  on public.app_telemetry_events(account_id, event_at desc);

create index if not exists app_telemetry_name_event_at_idx
  on public.app_telemetry_events(event_name, event_at desc);

create index if not exists app_telemetry_version_event_at_idx
  on public.app_telemetry_events(app_version, event_at desc);
